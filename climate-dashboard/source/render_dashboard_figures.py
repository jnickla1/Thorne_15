def arr(x): return np.asarray(x,dtype=float)
def avg(x):
    a=arr(x); n=np.isfinite(a).sum(axis=0)
    return np.divide(np.nansum(a,axis=0),n,out=np.full(a.shape[1:],np.nan),where=n>0)
def likelihood(p):
    if p<.01:return 'exceptionally unlikely'
    if p<=.05:return 'extremely unlikely'
    if p<.1:return 'very unlikely'
    if p<.33:return 'unlikely'
    if p<.66:return 'about as likely as not'
    if p<.9:return 'likely'
    if p<.99:return 'very likely'
    return 'virtually certain'

def short_label(method, label):
    if method.startswith('GWI'): return 'GWI (anthropogenic)' if 'anthro' in method else 'GWI (total)'
    if method.startswith('EBM'): return 'EBM–Kalman filter'
    return label

def rate_label(method, label):
    if method.startswith('GWI'): return 'GWI'
    if method.startswith('EBM'): return 'EBM–KF'
    if method.startswith('FaIR'): return 'FaIR'
    if method.startswith('LOWESS'): return 'LOWESS'
    if method.startswith('Kal'): return 'Kalman'
    return label.replace(' combination','')
def density(prob,years,j):
    start=[1970,1990,2005][j]; end=[2005,2025,2025][j]
    ix=(years>=start)&(years<=end); p=prob[ix]
    p=np.maximum.accumulate(np.nan_to_num(p,nan=0)); pdf=np.clip(np.diff(p,prepend=p[0]),0,None)
    tf=years[ix][0]+np.arange(len(pdf)*12)/12
    return tf,gaussian_filter1d(np.repeat(pdf,12),12,mode='nearest')

