def main():
    p=argparse.ArgumentParser(); p.add_argument('--data',type=Path,default=Path(__file__).resolve().parents[1]/'data'); p.add_argument('--outdir',type=Path,default=Path(__file__).resolve().parents[1]/'figures');p.add_argument('--primary-only',action='store_true');args=p.parse_args();args.outdir.mkdir(exist_ok=True,parents=True)
    manifest=[]
    if not args.primary_only:
        for b in ['rpi','satcal']:
            for g in ['real','anthro']:
                d=json.loads((args.data/f'{b}_{g}.json').read_text())
                for m in d['methods']:
                    for bg in ['raw','smoothed','centered20']:
                        fn=render(d,m,bg,'headline',args.outdir)
                        manifest.append(dict(baseline=b,goal=g,method=m,background=bg,file=fn))
                print('Rendered',b,g,flush=True)
    d=json.loads((args.data/'rpi_real.json').read_text());render(d,'PIVW_comb','raw','headline',args.outdir,expanded=False,primary=True)
    if manifest:(args.outdir/'manifest.json').write_text(json.dumps(manifest,indent=2))

if __name__=='__main__':main()
